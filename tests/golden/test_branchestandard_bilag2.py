FRAKTILER = (0.05, 0.95)


def tidspunkter():
    return [Tidspunkt(indbetaling=r[2], udbetalingsfaktor=r[3], mu=r[4], sigma=r[5]) for r in BILAG2]


def test_trin1_middelvaerdi_og_varians():
    # Initialopsparingen (1.000) og præmien ved t = 0 (100) er depotet ved start.
    fordelinger = trin1(1000, tidspunkter())
    for r, f in zip(BILAG2, fordelinger):
        assert f.middel == pytest.approx(r[6], rel=1e-12), r[0]
        assert f.varians == pytest.approx(r[7], rel=1e-9, abs=1e-6), r[0]


def test_fraktiler_af_depotet():
    for r, f in zip(BILAG2, trin1(1000, tidspunkter())):
        assert fraktil(f, FRAKTILER[0]) == pytest.approx(r[8], rel=1e-9), r[0]
        assert fraktil(f, FRAKTILER[1]) == pytest.approx(r[9], rel=1e-9), r[0]


def test_trin2_tre_afkaststier():
    tider = tidspunkter()
    stier = trin2(tider, trin1(1000, tider), FRAKTILER)
    assert len(stier.lav) == len(stier.forventet) == len(stier.hoej) == len(BILAG2) - 1
    for r, lav, forv, hoej in zip(BILAG2[1:], stier.lav, stier.forventet, stier.hoej):
        assert lav == pytest.approx(r[10], rel=1e-9), r[0]
        assert hoej == pytest.approx(r[11], rel=1e-9), r[0]
        assert forv == pytest.approx(r[12], rel=1e-12), r[0]


def test_middelstien_er_det_forventede_afkast():
    tider = tidspunkter()
    stier = trin2(tider, trin1(1000, tider), FRAKTILER)
    assert stier.forventet[0] == pytest.approx(math.exp(tider[0].mu) - 1)


def test_depotet_loeber_toer_seneste_afkast_bruges():
    # Henstillingen appendix 1, løsning 1: Kan stien ikke beregnes, fordi depotet er tømt, bruges
    # afkastet fra den seneste periode, hvor det kan beregnes.
    tider = tidspunkter() + [Tidspunkt(indbetaling=0, udbetalingsfaktor=0, mu=0.019, sigma=0.04)] * 2
    stier = trin2(tider, trin1(1000, tider), FRAKTILER)
    assert stier.lav[-1] == stier.lav[-2] == stier.lav[len(BILAG2) - 2]
    assert stier.hoej[-1] == stier.hoej[len(BILAG2) - 2]
    assert all(math.isfinite(x) for x in stier.lav + stier.hoej)
